soundToggle.addEventListener('click', () => {
  soundEnabled = !soundEnabled;
  soundToggle.classList.toggle('active', soundEnabled);
  soundIcon.className = soundEnabled ? 'fa-solid fa-volume-high' : 'fa-solid fa-volume-xmark';
  // eslint-disable-next-line
  if (!audioCtx) audioCtx = new (window.AudioContext || window['webkitAudioContext'])();
});

function playHoverSound() {
  if (!soundEnabled || !audioCtx) return;
  const oscillator = audioCtx.createOscillator();
  const gainNode = audioCtx.createGain();
  oscillator.connect(gainNode);
  gainNode.connect(audioCtx.destination);
  oscillator.type = 'sine';
  oscillator.frequency.setValueAtTime(800, audioCtx.currentTime);
  oscillator.frequency.exponentialRampToValueAtTime(1200, audioCtx.currentTime + 0.05);
  gainNode.gain.setValueAtTime(0.03, audioCtx.currentTime);
  gainNode.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + 0.1);
  oscillator.start(audioCtx.currentTime);
  oscillator.stop(audioCtx.currentTime + 0.1);
}

document.querySelectorAll('a, button, .project-card, .service-card').forEach(el => {
  el.addEventListener('mouseenter', playHoverSound);
});

/* ============================================================
   CURSOR TRAIL SPARKS
============================================================ */
const sparkColors = ['#cc0000','#e63333','#ff6b6b','#8b0000','#ff4444'];
let lastSparkX = 0, lastSparkY = 0;

document.addEventListener('mousemove', e => {
  const dx = e.clientX - lastSparkX;
  const dy = e.clientY - lastSparkY;
  if (Math.abs(dx) + Math.abs(dy) < 12) return;
  lastSparkX = e.clientX;
  lastSparkY = e.clientY;

  const spark = document.createElement('div');
  spark.className = 'cursor-spark';
  spark.style.cssText = `
    left: ${e.clientX}px;
    top: ${e.clientY}px;
    width: ${4 + Math.random() * 5}px;
    height: ${4 + Math.random() * 5}px;
    background: ${sparkColors[Math.floor(Math.random() * sparkColors.length)]};
    box-shadow: 0 0 6px currentColor;
  `;
  document.body.appendChild(spark);
  setTimeout(() => spark.remove(), 550);
});

